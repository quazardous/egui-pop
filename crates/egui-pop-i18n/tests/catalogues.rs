//! egui-pop's own catalogues (`locales/`) against what egui-pop shows:
//! the English one is generated from the strings of the code and the
//! declarations of every egui-pop plugin, and must be up to date; every
//! other locale must translate all of it, from the English of now.
//! Regenerate the English and stamp new translations with
//! `UPDATE_CATALOGUES=1 cargo test -p egui-pop-i18n --test catalogues`.

use std::path::Path;

use egui_pop_api::App;
use egui_pop_core::strings::StrKey;
use egui_pop_i18n::check::{self, Catalogs};
use egui_pop_i18n::extract::{self, English, Found, Messages};

/// The locales egui-pop translates itself into.
const TRANSLATED: &[&str] = &["fr"];

const HEADER: &str = "\
# egui-pop's own strings and what its plugins declare, in English.
# Generated by `UPDATE_CATALOGUES=1 cargo test -p egui-pop-i18n --test
# catalogues`: do not edit. Translations live in ../<locale>/egui-pop.ftl.
";

fn strings(list: &[StrKey], origin: &str) -> Vec<Found> {
    list.iter()
        .map(|k| Found {
            key: k.key.into(),
            english: English::Pattern(k.fallback.into()),
            origin: origin.into(),
        })
        .collect()
}

/// Everything egui-pop shows, by key.
fn messages() -> Messages {
    let ctx = egui::Context::default();
    let app = App::builder()
        .plugins(egui_pop_api::DefaultPlugins)
        .plugin(egui_pop_api::devtools::DevtoolsPlugin::default())
        .plugin(egui_pop_api::frame::FramePlugin::system())
        .plugin(egui_pop_api::strips::StripsPlugin::default())
        .plugin(egui_pop_i18n::I18nPlugin::new())
        .plugin(egui_pop_i18n::ShowKeys)
        .build(&ctx)
        .expect("egui-pop's plugins build");
    let mut found = extract::declarations(app.handle(), &[]);
    // The language setting's choices are each language's own name,
    // generated at connect: not catalogue text.
    found.retain(|f| {
        !f.key.starts_with("setting-appearance-language-choice-") || f.key.ends_with("-system")
    });
    // Says what this machine's system answered: not catalogue text (the
    // code's English shows in every language).
    found.retain(|f| f.key != "setting-appearance-focus.description");
    found.extend(strings(egui_pop_core::strings::ALL, "egui-pop-core"));
    found.extend(strings(egui_pop_api::strings::ALL, "egui-pop-api"));
    found.extend(strings(
        egui_pop_viewport::strings::ALL,
        "egui-pop-viewport",
    ));
    extract::messages(&found).expect("one English text per key")
}

fn dir() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("locales")
}

#[test]
fn the_english_catalogue_is_generated_from_the_code() {
    let messages = messages();
    let path = dir().join("en/egui-pop.ftl");
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    let fresh = extract::english(&messages, HEADER);
    if std::env::var_os("UPDATE_CATALOGUES").is_some() {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    assert!(
        current == fresh,
        "locales/en/egui-pop.ftl is out of date: run UPDATE_CATALOGUES=1 cargo test -p egui-pop-i18n --test catalogues"
    );
}

#[test]
fn every_locale_translates_everything_and_nothing_else() {
    let messages = messages();
    let mut catalogs = Catalogs::read(&dir()).unwrap();
    if std::env::var_os("UPDATE_CATALOGUES").is_some() {
        // New translations are stamped with the English they were made
        // from; translations of changed English are reviewed by hand.
        for locale in TRANSLATED {
            let hashes = check::stamp(&catalogs, locale, false).unwrap();
            std::fs::write(
                dir().join(locale).join(check::HASHES),
                check::write_hashes(&hashes),
            )
            .unwrap();
        }
        catalogs = Catalogs::read(&dir()).unwrap();
    }
    let report = check::check(&catalogs);
    assert!(report.faults.is_empty(), "{report}");
    for l in &report.locales {
        assert!(
            l.changed.is_empty() && l.unstamped.is_empty(),
            "{report}review the translations, then stamp them (UPDATE_CATALOGUES=1)"
        );
    }
    for l in extract::report(&catalogs, &messages) {
        assert!(
            l.missing.is_empty(),
            "{}: missing {:?}",
            l.locale,
            l.missing
        );
        assert!(l.unused.is_empty(), "{}: unused {:?}", l.locale, l.unused);
    }
}
