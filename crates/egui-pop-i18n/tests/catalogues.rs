//! egui-pop's own catalogues (`locales/`) against what egui-pop shows:
//! the English one is generated from the strings of the code and the
//! declarations of every egui-pop plugin, and must be up to date; every
//! other locale must translate all of it, from the English of now.
//! Regenerate the English and stamp new translations with
//! `UPDATE_CATALOGUES=1 cargo test -p egui-pop-i18n --test catalogues`,
//! with as many test threads as you like.

use std::fs::File;
use std::path::Path;

use egui_pop_api::App;
use egui_pop_core::strings::StrKey;
use egui_pop_i18n::check::{self, Catalogs};
use egui_pop_i18n::extract::{self, English, Found, Messages};

/// The locales egui-pop translates itself into.
const TRANSLATED: &[&str] = &["fr"];

const HEADER: &str = "\
# egui-pop's own strings and what its plugins declare, in English.
# Generated by `UPDATE_CATALOGUES=1 cargo test -p egui-pop-i18n --test
# catalogues`: do not edit. Translations live in ../<locale>/egui-pop.ftl.
";

fn strings(list: &[StrKey], origin: &str) -> Vec<Found> {
    list.iter()
        .map(|k| Found {
            key: k.key.into(),
            english: English::Pattern(k.fallback.into()),
            origin: origin.into(),
        })
        .collect()
}

/// The platform services, on simulated desktops (nothing reaches this
/// machine's), writing under `scratch`.
fn platform(b: egui_pop_api::AppBuilder, scratch: &Path) -> egui_pop_api::AppBuilder {
    use egui_pop_platform::{crash, focus, instance, keys, logs, notify, tray};
    b.plugin(instance::InstancePlugin::new(instance::Instance::detached(
        instance::Launch::default(),
    )))
    .plugin(notify::NotifyPlugin::new("egui-pop").backend(notify::Simulated::default()))
    .plugin(tray::TrayPlugin::new("egui-pop").backend(tray::Simulated::default()))
    .plugin(
        keys::SystemKeysPlugin::new("org.egui_pop.catalogue").backend(keys::Simulated::default()),
    )
    .plugin(logs::LogsPlugin::new("egui-pop").logs(logs::Logs::new(scratch, "catalogue")))
    .plugin(
        crash::CrashPlugin::new("egui-pop", "0")
            .dir(scratch.join("crashes"))
            .hook(false),
    )
    .plugin(focus::FocusModePlugin::fixed(Default::default()))
    // Opens no clipboard until a copy or a paste.
    .plugin(egui_pop_platform::clipboard::SystemClipboardPlugin::new())
}

/// Everything egui-pop shows, by key.
fn messages() -> Messages {
    // One directory per call: the tests run at once.
    static CALLS: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let call = CALLS.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let scratch =
        std::env::temp_dir().join(format!("egui-pop-catalogues-{}-{call}", std::process::id()));
    let ctx = egui::Context::default();
    let app = platform(App::builder(), &scratch)
        .plugins(egui_pop_api::DefaultPlugins)
        .plugin(egui_pop_api::devtools::DevtoolsPlugin::default())
        .plugin(egui_pop_api::frame::FramePlugin::system())
        .plugin(egui_pop_api::strips::StripsPlugin::default())
        .plugin(egui_pop_api::jobs::JobsPlugin::default())
        .plugin(egui_pop_api::theme_editor::ThemeEditorPlugin)
        .plugin(egui_pop_api::tips::TipsPlugin)
        .plugin(egui_pop_api::about::AboutPlugin::default())
        .plugin(egui_pop_api::contexts::ContextsPlugin::default())
        .plugin(egui_pop_api::history_view::HistoryPlugin::default())
        .plugin(egui_pop_api::clipboard::ClipboardPlugin)
        .plugin(egui_pop_i18n::I18nPlugin::new())
        .plugin(egui_pop_i18n::ShowKeys)
        .plugin(egui_pop_views::ViewsPlugin)
        .plugin(egui_pop_views::library::LibraryPlugin)
        .plugin(egui_pop_views::viewer::ViewerPlugin::default())
        .plugin(egui_pop_editors::EditorsPlugin)
        .plugin(egui_pop_editors::TerminalPlugin)
        .plugin(egui_pop_editors::JobConsolesPlugin)
        .build(&ctx)
        .expect("egui-pop's plugins build");
    let mut found = extract::declarations(app.handle(), &[]);
    // The language setting's choices are each language's own name,
    // generated at connect: not catalogue text.
    found.retain(|f| {
        !f.key.starts_with("setting-appearance-language-choice-") || f.key.ends_with("-system")
    });
    // Says what this machine's system answered: not catalogue text (the
    // code's English shows in every language).
    found.retain(|f| f.key != "setting-appearance-focus.description");
    found.extend(strings(egui_pop_core::strings::ALL, "egui-pop-core"));
    found.extend(strings(egui_pop_api::strings::ALL, "egui-pop-api"));
    found.extend(strings(
        egui_pop_viewport::strings::ALL,
        "egui-pop-viewport",
    ));
    found.extend(strings(
        egui_pop_platform::strings::ALL,
        "egui-pop-platform",
    ));
    found.extend(strings(egui_pop_views::strings::ALL, "egui-pop-views"));
    found.extend(strings(egui_pop_editors::strings::ALL, "egui-pop-editors"));
    drop(app);
    let _ = std::fs::remove_dir_all(&scratch);
    extract::messages(&found).expect("one English text per key")
}

fn dir() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("locales")
}

/// The right to touch the catalogues' files, until dropped. A file lock
/// and not a mutex: nextest runs each test in a process of its own, and each
/// `File` conflicts with the others in one process too.
fn writing_lock() -> File {
    let lock = File::create(Path::new(env!("CARGO_TARGET_TMPDIR")).join("catalogues.lock"))
        .expect("the lock file opens");
    lock.lock().expect("the lock is taken");
    lock
}

/// Regenerates the English under `dir`, then stamps new translations from
/// that English. `std::fs::write` empties a file before filling it, and a
/// stamp made from an English caught then drops every key: only under
/// [`writing_lock`].
fn update(dir: &Path, messages: &Messages) {
    std::fs::write(
        dir.join("en/egui-pop.ftl"),
        extract::english(messages, HEADER),
    )
    .unwrap();
    let catalogs = Catalogs::read(dir).unwrap();
    for locale in TRANSLATED {
        // New translations are stamped with the English they were made
        // from; translations of changed English are reviewed by hand.
        let hashes = check::stamp(&catalogs, locale, false).unwrap();
        std::fs::write(
            dir.join(locale).join(check::HASHES),
            check::write_hashes(&hashes),
        )
        .unwrap();
    }
}

/// With `UPDATE_CATALOGUES`, the update, whichever test comes first; the lock
/// it returns keeps the other test's update off the files this test reads.
fn update_when_asked(messages: &Messages) -> Option<File> {
    std::env::var_os("UPDATE_CATALOGUES").map(|_| {
        let lock = writing_lock();
        update(&dir(), messages);
        lock
    })
}

#[egui_pop_test_macros::critical]
#[test]
fn the_english_catalogue_is_generated_from_the_code() {
    let messages = messages();
    let _updating = update_when_asked(&messages);
    let path = dir().join("en/egui-pop.ftl");
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    let fresh = extract::english(&messages, HEADER);
    assert!(
        current == fresh,
        "locales/en/egui-pop.ftl is out of date: run UPDATE_CATALOGUES=1 cargo test -p egui-pop-i18n --test catalogues"
    );
}

#[egui_pop_test_macros::critical]
#[test]
fn every_locale_translates_everything_and_nothing_else() {
    let messages = messages();
    let _updating = update_when_asked(&messages);
    let catalogs = Catalogs::read(&dir()).unwrap();
    let report = check::check(&catalogs);
    assert!(report.faults.is_empty(), "{report}");
    for l in &report.locales {
        assert!(
            l.changed.is_empty() && l.unstamped.is_empty(),
            "{report}review the translations, then stamp them (UPDATE_CATALOGUES=1)"
        );
    }
    for l in extract::report(&catalogs, &messages) {
        assert!(
            l.missing.is_empty(),
            "{}: missing {:?}",
            l.locale,
            l.missing
        );
        assert!(l.unused.is_empty(), "{}: unused {:?}", l.locale, l.unused);
    }
}

/// Updates at once, each under the lock as the tests' are, on a copy of the
/// catalogues: none finds the stamps other than one update alone leaves them.
#[test]
fn updates_at_once_leave_every_stamp_in_place() {
    let messages = messages();
    let scratch =
        Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("catalogues-{}", std::process::id()));
    {
        let _lock = writing_lock();
        for file in ["en/egui-pop.ftl", "fr/egui-pop.ftl", "fr/english.hashes"] {
            let to = scratch.join(file);
            std::fs::create_dir_all(to.parent().unwrap()).unwrap();
            std::fs::copy(dir().join(file), to).unwrap();
        }
        update(&scratch, &messages);
    }
    let stamps = scratch.join("fr").join(check::HASHES);
    let alone = std::fs::read_to_string(&stamps).unwrap();
    assert!(
        alone.lines().count() > 1000,
        "{} lines",
        alone.lines().count()
    );
    std::thread::scope(|threads| {
        for _ in 0..4 {
            threads.spawn(|| {
                for _ in 0..10 {
                    let _lock = writing_lock();
                    update(&scratch, &messages);
                    assert!(std::fs::read_to_string(&stamps).unwrap() == alone);
                }
            });
        }
    });
    let _ = std::fs::remove_dir_all(&scratch);
}
