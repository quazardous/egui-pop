//! `docs/hosts.md`, written from the declarations: the hosts and their
//! offers, the components and their needs, the matrix of [`check`]
//! verdicts, the rules, the conditions and the reasons, and the counts.
//! `cargo xtask hosts` writes it; a test fails when the committed page
//! differs from a fresh one.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::{
    CODES, ClaimKey, CodeKind, Dismiss, Display, Fit, FocusPolicy, HostDisplay, HostOffer,
    HostSize, Instances, Keep, Keyboard, Lifetime, Mountable, Rule, Window, Workers, check,
};

/// Where the mount tests are, as the page links them.
pub const MOUNT_TESTS: &str = "crates/egui-pop-gallery/tests/mounts.rs";

/// The page.
pub fn render(components: &[Mountable], hosts: &[HostOffer]) -> String {
    let mut out = String::new();
    let o = &mut out;
    head(o);
    hosts_section(o, hosts);
    components_section(o, components);
    let cells: Vec<Vec<Fit>> = components
        .iter()
        .map(|m| hosts.iter().map(|h| check(m, h)).collect())
        .collect();
    matrix(o, components, hosts, &cells);
    counts(o, hosts, &cells);
    rules(o);
    codes(o);
    notes(o);
    out
}

fn head(o: &mut String) {
    o.push_str(
        "# Hosts and components: what can live where

<!-- Generated by `cargo xtask hosts` from the declarations; do not edit. -->

A **host** is a place egui-pop draws content in (a docked panel, a
floating palette, a dialog). A **component** is something drawn there
(the image viewport, the tree, the terminal). Each cell answers: can
this component be mounted in this host, and if not, why not?

This page is generated from the mount contract
([ADR 0013](adr/0013-mount-contract.md)): each component declares what it
needs (`Mountable`), each host what it offers (`HostOffer`), and each
cell is the verdict of `egui_pop::model::mount::check` on the pair.
`cargo xtask hosts` writes it, and a test fails when the committed page
is stale. In an application, `AppHandle::where_can` gives the same
verdicts and the debug bridge's `mounts` collector shows them to agents.

## How to read a cell

| Cell | Status | Meaning |
|---|---|---|
| `yes` | fits | Nothing in the way; mounted by the mount tests. |
| `if c…` | fits under conditions | Fits, under every condition named (see [Conditions](#conditions)). |
| `D…` | does not fit, by design | It would break a named rule on purpose; the rule says what to do instead. |
| `E…` | does not fit, egui-pop limit | egui-pop does not do it yet; an estimated cost is given. |
| `U…` | does not fit, upstream limit | egui, eframe or another dependency cannot do it; linked to [upstream.md](upstream.md). |
| `…*` | not tried | Fits by the declarations, but no headless test can mount it there (see [Notes](#notes)): a gap, not a refusal. |

\"Impossible\" is only ever a `D` or a `U`. An `E` is work not done yet.
",
    );
}

fn hosts_section(o: &mut String, hosts: &[HostOffer]) {
    o.push_str(
        "
## The hosts

| Column | Host | Where in the code | What it offers |
|---|---|---|---|
",
    );
    for h in hosts {
        let _ = writeln!(
            o,
            "| **{}** | {} | {} | {} |",
            h.code,
            h.name,
            code_list(&h.source),
            offer(h)
        );
    }
    o.push_str(
        "
Hosts that take **no component at all**, by design, and so have no column:

- **Toast** (`toasts`): text, a level, actions and a job's progress;
  data only. A component goes in the jobs centre or a panel the toast's
  action opens.
- **Menus and the command palette**: items, not content.
- **A palette outside the main window** (a native utility window): not
  built, and blocked upstream, U3.
",
    );
}

/// `a, b` as code spans.
fn code_list(s: &str) -> String {
    s.split(", ")
        .filter(|p| !p.is_empty())
        .map(|p| format!("`{p}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn keys(keys: &[ClaimKey]) -> String {
    keys.iter().map(|k| k.name()).collect::<Vec<_>>().join(", ")
}

/// An offer in one line.
fn offer(h: &HostOffer) -> String {
    let mut parts: Vec<String> = Vec::new();
    parts.push(
        match h.size {
            HostSize::Fill => "a whole rect",
            HostSize::Given => "a size of its own declaration",
            HostSize::Content => "a bounded width, the content's height",
            HostSize::Row => "one row",
            HostSize::NoUi => "**no `Ui`: data only**",
        }
        .to_string(),
    );
    if h.resizable {
        parts.push("resized by the user".into());
    } else if h.size != HostSize::NoUi {
        parts.push("not resizable".into());
    }
    parts.push(
        match h.focus {
            FocusPolicy::Shared => "shared focus",
            FocusPolicy::ClickInto => "the keyboard once clicked into",
            FocusPolicy::ModalExclusive => "modal: the whole keyboard",
            FocusPolicy::None => "no keyboard",
        }
        .to_string(),
    );
    if !h.owns_keys.is_empty() {
        let honoured = if h.honours_claims {
            " (given to a content claiming them)"
        } else {
            ""
        };
        parts.push(format!("owns {}{honoured}", keys(&h.owns_keys)));
    }
    if !h.dismissed_by.is_empty() {
        let by: Vec<&str> = h
            .dismissed_by
            .iter()
            .map(|d| match d {
                Dismiss::Answer => "an answer",
                Dismiss::Escape => "Escape",
                Dismiss::OutsideClick => "a click outside",
            })
            .collect();
        parts.push(format!("closed by {}", by.join(", ")));
    }
    parts.push(
        match h.lifetime {
            Lifetime::Persistent => "persistent",
            Lifetime::Transient => "transient",
        }
        .into(),
    );
    parts.push(
        match h.window {
            Window::Main => "main window",
            Window::Auxiliary => "an auxiliary window",
            Window::FollowsPanel => "its panel's window",
        }
        .into(),
    );
    if h.size != HostSize::NoUi {
        parts.push(if h.keymap {
            "the keymap reaches it".into()
        } else {
            "**the keymap does not reach it**".into()
        });
    }
    if h.projection {
        parts.push("in the projection".into());
    }
    if !h.keeps.is_empty() {
        let kept: Vec<&str> = h
            .keeps
            .iter()
            .map(|k| match k {
                Keep::Place => "place",
                Keep::Size => "size",
                Keep::ViewValues => "view values",
            })
            .collect();
        parts.push(format!("keeps its {}", kept.join(", ")));
    }
    let mut gives = Vec::new();
    if h.gives_ui {
        gives.push("a `Ui`");
    }
    if h.gives_app {
        gives.push("an `AppHandle`");
    }
    if h.scope {
        gives.push("a focus scope");
    }
    if h.fault_boundary {
        gives.push("a fault boundary");
    }
    if !gives.is_empty() {
        parts.push(format!("gives {}", gives.join(", ")));
    }
    if h.gives_ui && !h.free_content {
        parts.push("descriptor fields only".into());
    }
    parts.push(match h.display {
        HostDisplay::Srgb => "sRGB".into(),
        HostDisplay::Wide => "wide gamut".into(),
    });
    if h.gives_ui && !h.cursor_images {
        parts.push("system cursors only".into());
    }
    if h.hides_content {
        parts.push("may hide its content".into());
    }
    let mut line = parts.join("; ");
    line.push('.');
    capitalise(&line)
}

fn capitalise(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(first) => first.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

fn components_section(o: &mut String, components: &[Mountable]) {
    o.push_str(
        "
## The components

| Row | Crate | What it needs |
|---|---|---|
",
    );
    for m in components {
        let _ = writeln!(o, "| {} | `{}` | {} |", m.name, m.from, needs(m));
    }
}

/// Needs in one line.
fn needs(m: &Mountable) -> String {
    let mut parts: Vec<String> = Vec::new();
    let mut k = match m.keyboard {
        Keyboard::None => "no keyboard".to_string(),
        Keyboard::Hover => "keys while hovered".into(),
        Keyboard::Focus => "keys when focused".into(),
        Keyboard::Exclusive => "**every key** while focused".into(),
    };
    if !m.claims.is_empty() {
        let _ = write!(k, ", claims {}", keys(&m.claims));
    }
    parts.push(k);
    match (&m.surface, m.keymap) {
        (Some(s), _) => parts.push(format!("keymap surface `{s}`")),
        (None, true) => parts.push("keymap bindings".into()),
        (None, false) => {}
    }
    let mut pointer = Vec::new();
    if m.pointer.drag {
        pointer.push("drags");
    }
    if m.pointer.drag_out {
        pointer.push("drags out");
    }
    if m.pointer.wheel {
        pointer.push("wheel");
    }
    if m.pointer.cursor_images {
        pointer.push("bitmap cursors");
    }
    if !pointer.is_empty() {
        parts.push(pointer.join(", "));
    }
    if m.workers == Workers::DrainedWhenDrawn {
        parts.push(if m.keep_under_modal {
            "workers, drained when drawn, kept under a modal".into()
        } else {
            "workers, drained when drawn".into()
        });
    }
    match m.display {
        Display::Srgb => {}
        Display::WideWanted => parts.push("wide gamut wanted".into()),
        Display::WideRequired => parts.push("**wide gamut required**".into()),
    }
    let mut size = String::new();
    let [w, h] = m.size.min;
    if w > 0.0 || h > 0.0 {
        let _ = write!(size, "at least {w} by {h}");
    }
    if let Some([w, h]) = m.size.preferred {
        if !size.is_empty() {
            size.push_str(", ");
        }
        let _ = write!(size, "{w} by {h} preferred");
    }
    if let Some([w, h]) = m.size.max {
        if !size.is_empty() {
            size.push_str(", ");
        }
        let _ = write!(size, "at most {w} by {h}");
    }
    if let Some(a) = m.size.aspect {
        if !size.is_empty() {
            size.push_str(", ");
        }
        let _ = write!(size, "aspect {a}");
    }
    if m.size.fills {
        if !size.is_empty() {
            size.push_str(", ");
        }
        size.push_str("fills");
    }
    if !size.is_empty() {
        parts.push(size);
    }
    if m.instances == Instances::Single {
        parts.push("**one per application**".into());
    }
    if let Some(key) = &m.view_state {
        parts.push(format!("view state `{key}`"));
    }
    if m.app {
        parts.push("an `AppHandle`".into());
    }
    if m.asks {
        parts.push("asks a question".into());
    }
    if m.session {
        parts.push("**holds a session**".into());
    }
    if m.popups {
        parts.push("popups of its own".into());
    }
    if m.preview {
        parts.push("a preview mode".into());
    }
    if m.descriptor_field {
        parts.push("a descriptor field".into());
    }
    parts.push(format!("role `{}`", m.role));
    let mut line = parts.join("; ");
    line.push('.');
    capitalise(&line)
}

/// A cell, with `*` when the host cannot be mounted headless.
fn cell(fit: &Fit, host: &HostOffer) -> String {
    let star = if fit.fits() && !host.headless {
        "*"
    } else {
        ""
    };
    format!("`{}{star}`", fit.cell())
}

fn matrix(o: &mut String, components: &[Mountable], hosts: &[HostOffer], cells: &[Vec<Fit>]) {
    o.push_str("\n## The matrix\n\n| Component |");
    for h in hosts {
        let _ = write!(o, " {} |", h.code);
    }
    o.push_str("\n|---|");
    for _ in hosts {
        o.push_str("---|");
    }
    o.push('\n');
    for (m, row) in components.iter().zip(cells) {
        let _ = write!(o, "| {} |", m.name);
        for (fit, h) in row.iter().zip(hosts) {
            let _ = write!(o, " {} |", cell(fit, h));
        }
        o.push('\n');
    }
    let _ = writeln!(
        o,
        "\nColumns: {}.",
        hosts
            .iter()
            .map(|h| format!("**{}** {}", h.code, h.name.to_lowercase()))
            .collect::<Vec<_>>()
            .join(", ")
    );
}

fn counts(o: &mut String, hosts: &[HostOffer], cells: &[Vec<Fit>]) {
    let (mut yes, mut under, mut not_tried) = (0, 0, 0);
    let mut refused: BTreeMap<(u8, &'static str), usize> = BTreeMap::new();
    let mut total = 0;
    for row in cells {
        for (fit, h) in row.iter().zip(hosts) {
            total += 1;
            if fit.fits() && !h.headless {
                not_tried += 1;
            }
            match fit {
                Fit::Yes => yes += 1,
                Fit::Under { .. } => under += 1,
                Fit::No { refusal, .. } => {
                    let rank = match refusal.kind {
                        CodeKind::Design => 0,
                        CodeKind::Limit => 1,
                        CodeKind::Upstream => 2,
                        CodeKind::Condition => 3,
                    };
                    *refused.entry((rank, refusal.code)).or_default() += 1;
                }
            }
        }
    }
    let kind = |rank: u8| -> (usize, String) {
        let by: Vec<String> = refused
            .iter()
            .filter(|((r, _), _)| *r == rank)
            .map(|((_, code), n)| format!("`{code}` {n}"))
            .collect();
        let n = refused
            .iter()
            .filter(|((r, _), _)| *r == rank)
            .map(|(_, n)| n)
            .sum();
        (n, by.join(", "))
    };
    let (design, design_by) = kind(0);
    let (limit, limit_by) = kind(1);
    let (upstream, upstream_by) = kind(2);
    let with = |by: String| {
        if by.is_empty() {
            String::new()
        } else {
            format!(" ({by})")
        }
    };
    let _ = write!(
        o,
        "
## Counts

| Status | Cells |
|---|---|
| fits (`yes`) | {yes} |
| fits under conditions (`if`) | {under} |
| does not fit, by design{} | {design} |
| does not fit, egui-pop limit{} | {limit} |
| does not fit, upstream{} | {upstream} |
| **total** ({} components by {} hosts) | {total} |

Of the cells that fit, {not_tried} are not tried (`*`): their host
cannot be mounted headless.
",
        with(design_by),
        with(limit_by),
        with(upstream_by),
        cells.len(),
        hosts.len(),
    );
}

fn rules(o: &mut String) {
    o.push_str(
        "
## Rules

Each rule looks at one need against one offer. The worst verdict wins,
and every condition is kept.

| Rule | Name | What it compares |
|---|---|---|
",
    );
    for r in Rule::ALL {
        let _ = writeln!(o, "| {} | {} | {} |", r.number(), r.name(), r.compares());
    }
}

fn codes(o: &mut String) {
    o.push_str("\n## Conditions\n\n| Code | Condition |\n|---|---|\n");
    for c in CODES.iter().filter(|c| c.kind == CodeKind::Condition) {
        let _ = writeln!(o, "| {} | **{}.** {} |", c.code, c.title, c.text);
    }
    o.push_str("\n## Reasons\n\n### By design\n\n| Code | Rule | Do instead |\n|---|---|---|\n");
    for c in CODES.iter().filter(|c| c.kind == CodeKind::Design) {
        let _ = writeln!(
            o,
            "| {} | **{}.** {} | {} |",
            c.code, c.title, c.text, c.then
        );
    }
    o.push_str(
        "
D4 and D5 constrain how a component is used rather than where it fits:
no component of today asks a question of its own, and a dialog's body
draws a second choice inline.

### egui-pop limits

| Code | Limit | Estimated cost |
|---|---|---|
",
    );
    for c in CODES.iter().filter(|c| c.kind == CodeKind::Limit) {
        let _ = writeln!(
            o,
            "| {} | **{}.** {} | {} |",
            c.code, c.title, c.text, c.then
        );
    }
    o.push_str(
        "
E2 and the overlays E4 leaves in the main window appear as a condition
(c1) or as hosts that do not exist yet, not as refused cells.

### Upstream limits

| Code | Limit | Entry |
|---|---|---|
",
    );
    for c in CODES.iter().filter(|c| c.kind == CodeKind::Upstream) {
        let _ = writeln!(
            o,
            "| {} | **{}.** {} | {} |",
            c.code, c.title, c.text, c.then
        );
    }
    o.push_str(
        "
U1 and U2 degrade a cell (condition c3) rather than refuse it: no
component of today requires wide gamut. One that did (a mastering view)
would be refused outside the main window with U2.
",
    );
}

fn notes(o: &mut String) {
    let _ = write!(
        o,
        "
## Notes

- **Evidence.** `{MOUNT_TESTS}` mounts every component's gallery story
  in a mock host built from each offer that accepts it (the panel and
  the story by the gallery itself; the palette as an area of bounded
  width; the raw modal and the popover through the overlay stack; the
  custom dialog as a `Dialog::Custom`; the lines as one row), checks that
  nothing faults, that every interactive node has a name and that no
  diagnostic is raised, and checks that each refused mount is reported
  with its rule.
- **Workers.** Tile, thumbnail, tree and terminal sources run on the
  application's threads and keep running whatever the host, a modal
  included; their queues are drained when the component is drawn (c11).
- **Accessibility in an auxiliary window** is not tried: whether eframe
  gives an immediate viewport its own AccessKit tree has not been
  checked.
- **Tests across windows.** egui_kittest draws an immediate viewport
  inside the main one. The keys, dialogs and focus of auxiliary windows
  are tested with an immediate viewport renderer of the tests' own
  (`crates/egui-pop-api/tests/windows.rs`), each window's pass run with
  its own input, but no component is mounted in a real window there:
  the cells stay `*`.
- **Declarations can lie.** A component declared as reading keys when
  focused that reads one globally (the node graph's Space) shows a fit
  where it misbehaves; the mount tests are the guard.
"
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_page_shows_every_host_component_and_cell_with_counts() {
        let hosts = [
            HostOffer::new("panel", "P", "Docked panel").source("Ctx::panel, workbench"),
            HostOffer::new("popover", "O", "Popover")
                .size(HostSize::Content)
                .dismissed_by(&[Dismiss::OutsideClick])
                .lifetime(Lifetime::Transient),
            HostOffer::new("window", "W", "Auxiliary window").headless(false),
        ];
        let components = [
            Mountable::new("viewport", "Image viewport")
                .crate_name("egui-pop-viewport")
                .fills(),
            Mountable::new("terminal", "Terminal")
                .crate_name("egui-pop-editors")
                .session(),
        ];
        let page = render(&components, &hosts);
        assert!(page.contains("| **P** | Docked panel | `Ctx::panel`, `workbench` |"));
        assert!(
            page.contains("| Image viewport | `yes` | `if c1` | `yes*` |"),
            "{page}"
        );
        assert!(
            page.contains("| Terminal | `yes` | `D3` | `yes*` |"),
            "{page}"
        );
        assert!(
            page.contains("| does not fit, by design (`D3` 1) | 1 |"),
            "{page}"
        );
        assert!(page.contains("| **total** (2 components by 3 hosts) | 6 |"));
        assert!(page.contains("2 are not tried"));
        assert!(page.contains("| R11 | dialog content |"));
        assert!(page.contains("| c1 | **Content-sized host.**"));
        // Stable: the same declarations give the same page.
        assert_eq!(page, render(&components, &hosts));
    }
}
